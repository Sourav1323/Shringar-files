package com.shringar.repository;

import com.shringar.model.DesignerOrder;
import com.shringar.model.enums.BookingStatus;
import com.shringar.model.enums.PreferredTime;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;
import java.util.Optional;

@Repository
public interface DesignerOrderRepository extends JpaRepository<DesignerOrder, Long> {

    List<DesignerOrder> findByDesignerIdOrderByAppointmentDateDesc(Long designerId);

    Optional<DesignerOrder> findByBookingId(Long bookingId);

    List<DesignerOrder> findByDesignerIdAndAppointmentDate(Long designerId, LocalDate appointmentDate);

    /**
     * Strict Designer Slot Availability Check:
     * Returns true if this designer already has an active (non-cancelled) order
     * on this exact date and preferred time slot.
     */
    boolean existsByDesignerIdAndAppointmentDateAndPreferredTimeAndStatusIn(
            Long designerId, LocalDate appointmentDate, PreferredTime preferredTime, List<BookingStatus> statuses);

    /**
     * Total confirmed orders for a designer
     */
    @Query("SELECT COUNT(d) FROM DesignerOrder d WHERE d.designer.id = :designerId AND d.status <> com.shringar.model.enums.BookingStatus.CANCELLED")
    long countActiveOrdersByDesignerId(@Param("designerId") Long designerId);

    /**
     * Total earnings earned by a designer across all active orders
     */
    @Query("SELECT COALESCE(SUM(d.designerEarnings), 0) FROM DesignerOrder d WHERE d.designer.id = :designerId AND d.status <> com.shringar.model.enums.BookingStatus.CANCELLED")
    BigDecimal sumEarningsByDesignerId(@Param("designerId") Long designerId);

    /**
     * Total gross order value generated by a designer
     */
    @Query("SELECT COALESCE(SUM(d.orderTotal), 0) FROM DesignerOrder d WHERE d.designer.id = :designerId AND d.status <> com.shringar.model.enums.BookingStatus.CANCELLED")
    BigDecimal sumOrderTotalByDesignerId(@Param("designerId") Long designerId);
}
